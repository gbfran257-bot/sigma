    $aColumns = array('ov.referencia_ov', 'CONCAT(u.nombre_u, " ", u.apaterno_u, " ", u.amaterno_u)', 'srh.fecha_srh', 'srh.accion_srh');
    
    $aTables = array( 'seguimiento_referencias_hospital srh');
     
    // Indexed column (used for fast and accurate table cardinality) 
    $sIndexColumn = "srh.id_srh";
     
	 // Joins   
	$sJoin = 'LEFT JOIN usuarios u ON u.id_u = srh.usuario_srh LEFT JOIN orden_venta ov ON ov.id_ov = srh.referencia_ov_srh';

	
	$sWhere = "WHERE srh.id_rh_srh = " . $_GET['id_rh'];

	
